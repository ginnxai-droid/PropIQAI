begin;

create unique index followup_tasks_one_pending_callback_per_lead
  on public.followup_tasks (organization_id, lead_id)
  where task_type = 'CALLBACK' and status in ('PENDING', 'OVERDUE');

create or replace function public.assign_lead_secure(
  target_lead_id uuid,
  target_profile_id uuid
)
returns public.leads
language plpgsql
security invoker
set search_path = public
as $$
declare
  current_lead public.leads;
  updated_lead public.leads;
  deadline timestamptz;
  actor_id uuid;
begin
  actor_id := public.current_profile_id();

  select *
  into current_lead
  from public.leads
  where id = target_lead_id
  for update;

  if current_lead.id is null then
    raise exception 'lead not found' using errcode = 'P0002';
  end if;

  if not public.has_organization_role(
    current_lead.organization_id,
    array['OWNER', 'MANAGER', 'ADMIN']::public.organization_role[]
  ) then
    raise exception 'lead assignment is not permitted' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.organization_members membership
    where membership.organization_id = current_lead.organization_id
      and membership.profile_id = target_profile_id
      and membership.active = true
      and membership.role in ('MANAGER', 'EXECUTIVE')
  ) then
    raise exception 'assignee is not an active organization sales member'
      using errcode = '23503';
  end if;

  deadline := case
    when current_lead.priority = 'HOT' then now() + interval '10 minutes'
    else now() + interval '4 hours'
  end;

  update public.leads
  set
    assigned_to = target_profile_id,
    sla_deadline = deadline
  where id = target_lead_id
  returning * into updated_lead;

  insert into public.handoffs (
    organization_id,
    lead_id,
    assigned_to,
    reason,
    priority,
    sla_deadline,
    status
  )
  values (
    current_lead.organization_id,
    current_lead.id,
    target_profile_id,
    case
      when current_lead.site_visit_interest then 'SITE_VISIT_REQUEST'::public.handoff_reason
      else 'HOT_LEAD'::public.handoff_reason
    end,
    current_lead.priority,
    deadline,
    'PENDING'
  )
  on conflict (organization_id, lead_id)
    where status in ('PENDING', 'CONTACTED', 'ESCALATED')
  do update set
    assigned_to = excluded.assigned_to,
    reason = excluded.reason,
    priority = excluded.priority,
    sla_deadline = excluded.sla_deadline,
    status = 'PENDING',
    escalated_to = null,
    completed_at = null,
    updated_at = now();

  insert into public.followup_tasks (
    organization_id,
    lead_id,
    assigned_to,
    task_type,
    due_at,
    status,
    notes
  )
  values (
    current_lead.organization_id,
    current_lead.id,
    target_profile_id,
    'CALLBACK',
    deadline,
    'PENDING',
    'First response callback generated by secure lead assignment.'
  )
  on conflict (organization_id, lead_id)
    where task_type = 'CALLBACK' and status in ('PENDING', 'OVERDUE')
  do update set
    assigned_to = excluded.assigned_to,
    due_at = excluded.due_at,
    status = 'PENDING',
    notes = excluded.notes,
    updated_at = now();

  insert into public.sla_events (
    organization_id,
    lead_id,
    assigned_to,
    event_type,
    due_at
  )
  values (
    current_lead.organization_id,
    current_lead.id,
    target_profile_id,
    'FIRST_RESPONSE',
    deadline
  );

  insert into public.audit_logs (
    organization_id,
    actor_profile_id,
    entity_type,
    entity_id,
    action,
    old_values,
    new_values
  )
  values (
    current_lead.organization_id,
    actor_id,
    'lead',
    current_lead.id,
    'LEAD_ASSIGNED',
    jsonb_build_object('assigned_to', current_lead.assigned_to, 'sla_deadline', current_lead.sla_deadline),
    jsonb_build_object('assigned_to', target_profile_id, 'sla_deadline', deadline)
  );

  return updated_lead;
end;
$$;

revoke all on function public.assign_lead_secure(uuid, uuid) from public;
grant execute on function public.assign_lead_secure(uuid, uuid) to authenticated;

commit;
