import type { SupabaseClient } from "@supabase/supabase-js";
import type { AppConfig } from "../config";
import { throwDatabaseError, writeAuditLog } from "../database";
import { ApiError } from "../errors";
import { createAdminSupabaseClient } from "../supabase";
import {
  determineHandoffReasons,
  isUrgentHandoff,
  type HandoffReason,
} from "./handoffs";
import {
  calculateLeadScore,
  type CallbackResponsiveness,
  type EngagementQuality,
  type HandoffSignals,
} from "./scoring";
import { calculateSlaDeadline, escalationLevel } from "./sla";
import { upsertActiveAlert } from "./alerts";

interface WorkflowLead {
  id: string;
  organization_id: string;
  project_id: string;
  source: string;
  buyer_type: string;
  budget_min: number;
  budget_max: number;
  purchase_timeline: string;
  site_visit_interest: boolean;
  engagement_quality: EngagementQuality;
  callback_responsiveness: CallbackResponsiveness;
  handoff_signals: HandoffSignals;
  assigned_to: string | null;
  priority: "HOT" | "WARM" | "NURTURE" | "COLD";
}

export interface RunLeadWorkflowInput {
  organizationId: string;
  leadId: string;
  actorProfileId: string | null;
  requestedReasons?: HandoffReason[];
}

async function activeHandoff(
  admin: SupabaseClient,
  organizationId: string,
  leadId: string,
  reason: HandoffReason,
) {
  const { data, error } = await admin
    .from("handoffs")
    .select("*")
    .eq("organization_id", organizationId)
    .eq("lead_id", leadId)
    .eq("reason", reason)
    .in("status", ["PENDING", "CONTACTED", "ESCALATED"])
    .maybeSingle();
  throwDatabaseError(error, "The active handoff could not be checked.");
  return data;
}

async function persistHandoff(
  admin: SupabaseClient,
  input: {
    organizationId: string;
    leadId: string;
    assignedTo: string;
    reason: HandoffReason;
    priority: string;
    deadline: string;
  },
) {
  const existing = await activeHandoff(
    admin,
    input.organizationId,
    input.leadId,
    input.reason,
  );
  const values = {
    assigned_to: input.assignedTo,
    priority: input.priority,
    sla_deadline: input.deadline,
    status: "PENDING",
    escalation_level: 0,
    escalated_to: null,
    completed_at: null,
  };
  const operation = existing
    ? admin
        .from("handoffs")
        .update(values)
        .eq("organization_id", input.organizationId)
        .eq("id", existing.id)
    : admin.from("handoffs").insert({
        organization_id: input.organizationId,
        lead_id: input.leadId,
        reason: input.reason,
        ...values,
      });
  const { data, error } = await operation.select().single();
  throwDatabaseError(error, "The derived handoff could not be persisted.");
  return data;
}

async function persistCallbackTask(
  admin: SupabaseClient,
  lead: WorkflowLead,
  deadline: string,
) {
  const { data: existing, error: existingError } = await admin
    .from("followup_tasks")
    .select("id")
    .eq("organization_id", lead.organization_id)
    .eq("lead_id", lead.id)
    .eq("task_type", "CALLBACK")
    .in("status", ["PENDING", "OVERDUE"])
    .maybeSingle();
  throwDatabaseError(existingError, "The callback task could not be checked.");
  const values = {
    assigned_to: lead.assigned_to,
    due_at: deadline,
    status: "PENDING",
    notes: "Callback generated by the Stage 2 deterministic workflow.",
  };
  const operation = existing
    ? admin
        .from("followup_tasks")
        .update(values)
        .eq("organization_id", lead.organization_id)
        .eq("id", existing.id)
    : admin.from("followup_tasks").insert({
        organization_id: lead.organization_id,
        lead_id: lead.id,
        task_type: "CALLBACK",
        ...values,
      });
  const { error } = await operation;
  throwDatabaseError(error, "The callback task could not be persisted.");
}

async function persistSlaEvent(
  admin: SupabaseClient,
  lead: WorkflowLead,
  deadline: string,
  handoffId: string | null,
) {
  const { data: existing, error: existingError } = await admin
    .from("sla_events")
    .select("id")
    .eq("organization_id", lead.organization_id)
    .eq("lead_id", lead.id)
    .eq("event_type", "FIRST_RESPONSE")
    .is("completed_at", null)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();
  throwDatabaseError(existingError, "The SLA event could not be checked.");
  const values = {
    assigned_to: lead.assigned_to,
    handoff_id: handoffId,
    due_at: deadline,
    breached: false,
    escalation_level: 0,
  };
  const operation = existing
    ? admin
        .from("sla_events")
        .update(values)
        .eq("organization_id", lead.organization_id)
        .eq("id", existing.id)
    : admin.from("sla_events").insert({
        organization_id: lead.organization_id,
        lead_id: lead.id,
        event_type: "FIRST_RESPONSE",
        ...values,
      });
  const { error } = await operation;
  throwDatabaseError(error, "The SLA event could not be persisted.");
}

export async function runLeadWorkflow(
  config: AppConfig,
  input: RunLeadWorkflowInput,
) {
  const admin = createAdminSupabaseClient(config);
  const { data: lead, error: leadError } = await admin
    .from("leads")
    .select("*")
    .eq("organization_id", input.organizationId)
    .eq("id", input.leadId)
    .single();
  throwDatabaseError(leadError, "The lead workflow could not load the lead.");
  const { data: project, error: projectError } = await admin
    .from("projects")
    .select("price_min, price_max")
    .eq("organization_id", input.organizationId)
    .eq("id", lead.project_id)
    .single();
  throwDatabaseError(projectError, "The lead workflow could not load the project.");
  if (!project) {
    throw new ApiError(400, "The lead project is invalid.", "INVALID_PROJECT");
  }

  const score = calculateLeadScore({
    projectPriceMin: Number(project.price_min),
    projectPriceMax: Number(project.price_max),
    budgetMin: Number(lead.budget_min),
    budgetMax: Number(lead.budget_max),
    purchaseTimeline: lead.purchase_timeline,
    buyerType: lead.buyer_type,
    siteVisitInterest: lead.site_visit_interest,
    engagementQuality: lead.engagement_quality,
    source: lead.source,
    callbackResponsiveness: lead.callback_responsiveness,
    handoffSignals: lead.handoff_signals ?? {},
  });

  const { data: scoredLead, error: scoreError } = await admin
    .from("leads")
    .update({
      score: score.total,
      priority: score.priority,
      score_components: score.components,
      scoring_version: score.version,
      score_explanation: score.explanation,
      recalculated_at: score.recalculatedAt,
    })
    .eq("organization_id", input.organizationId)
    .eq("id", input.leadId)
    .select("*")
    .single();
  throwDatabaseError(scoreError, "The lead score could not be persisted.");

  const derivedReasons = determineHandoffReasons({
    priority: score.priority,
    siteVisitInterest: scoredLead.site_visit_interest,
    budgetMax: Number(scoredLead.budget_max),
    projectPriceMax: Number(project.price_max),
    signals: scoredLead.handoff_signals ?? {},
  });
  const reasons = [
    ...new Set([...(input.requestedReasons ?? []), ...derivedReasons]),
  ];

  let deadline: Date | null = null;
  const handoffs = [];
  if (scoredLead.assigned_to) {
    const urgent = reasons.some(isUrgentHandoff);
    deadline = calculateSlaDeadline({
      priority: score.priority,
      urgentHandoff: urgent,
    });
    if (deadline) {
      for (const reason of reasons) {
        handoffs.push(
          await persistHandoff(admin, {
            organizationId: input.organizationId,
            leadId: input.leadId,
            assignedTo: scoredLead.assigned_to,
            reason,
            priority: score.priority,
            deadline: deadline.toISOString(),
          }),
        );
      }
      await persistCallbackTask(
        admin,
        scoredLead as WorkflowLead,
        deadline.toISOString(),
      );
      await persistSlaEvent(
        admin,
        scoredLead as WorkflowLead,
        deadline.toISOString(),
        handoffs[0]?.id ?? null,
      );
    }
  }

  const { error: deadlineError } = await admin
    .from("leads")
    .update({ sla_deadline: deadline?.toISOString() ?? null })
    .eq("organization_id", input.organizationId)
    .eq("id", input.leadId);
  throwDatabaseError(deadlineError, "The lead SLA deadline could not be persisted.");

  await writeAuditLog(admin, {
    organizationId: input.organizationId,
    actorProfileId: input.actorProfileId,
    entityType: "lead",
    entityId: input.leadId,
    action: "LEAD_WORKFLOW_RECALCULATED",
    newValues: {
      score: score.total,
      priority: score.priority,
      scoring_version: score.version,
      handoff_reasons: reasons,
      sla_deadline: deadline?.toISOString() ?? null,
    },
  });

  return { lead: { ...scoredLead, sla_deadline: deadline?.toISOString() ?? null }, score, handoffs };
}

export async function refreshSlaState(
  config: AppConfig,
  organizationId: string,
  now = new Date(),
) {
  const admin = createAdminSupabaseClient(config);
  const { data: events, error } = await admin
    .from("sla_events")
    .select(
      "id, lead_id, handoff_id, due_at, completed_at, breached, escalation_level",
    )
    .eq("organization_id", organizationId)
    .is("completed_at", null);
  throwDatabaseError(error, "SLA state could not be refreshed.");

  const { data: activeAlerts, error: alertError } = await admin
    .from("internal_alerts")
    .select("lead_id, alert_type")
    .eq("organization_id", organizationId)
    .in("status", ["OPEN", "ACKNOWLEDGED"]);
  throwDatabaseError(alertError, "Active SLA alerts could not be loaded.");
  const activeAlertKeys = new Set(
    (activeAlerts ?? []).map(
      (alert) => `${alert.lead_id}:${alert.alert_type}`,
    ),
  );
  const operations: Promise<unknown>[] = [];

  for (const event of events ?? []) {
    const level = escalationLevel(
      new Date(event.due_at),
      now,
      event.completed_at ? new Date(event.completed_at) : null,
    );
    if (event.breached !== (level > 0) || event.escalation_level !== level) {
      operations.push(
        (async () => {
          const { error: eventError } = await admin
            .from("sla_events")
            .update({ breached: level > 0, escalation_level: level })
            .eq("organization_id", organizationId)
            .eq("id", event.id);
          throwDatabaseError(eventError, "An SLA event could not be refreshed.");
          if (event.lead_id) {
            const { error: handoffError } = await admin
              .from("handoffs")
              .update({
                escalation_level: level,
                status: level > 0 ? "ESCALATED" : "PENDING",
              })
              .eq("organization_id", organizationId)
              .eq("lead_id", event.lead_id)
              .in("status", ["PENDING", "CONTACTED", "ESCALATED"])
              .neq("status", "RESOLVED");
            throwDatabaseError(
              handoffError,
              "A handoff escalation could not be refreshed.",
            );
          }
        })(),
      );
    }
    if (event.lead_id) {
      const millisecondsUntilDue = new Date(event.due_at).getTime() - now.getTime();
      const queueAlert = (
        alertType: "SLA_DUE_SOON" | "SLA_BREACHED" | "MANAGER_ESCALATION",
        severity: "WARNING" | "HIGH" | "CRITICAL",
        message: string,
      ) => {
        const key = `${event.lead_id}:${alertType}`;
        if (activeAlertKeys.has(key)) return;
        activeAlertKeys.add(key);
        operations.push(
          upsertActiveAlert(admin, {
            organizationId,
            leadId: event.lead_id,
            alertType,
            severity,
            message,
          }),
        );
      };
      if (
        level === 0 &&
        millisecondsUntilDue >= 0 &&
        millisecondsUntilDue <= 5 * 60_000
      ) {
        queueAlert(
          "SLA_DUE_SOON",
          "WARNING",
          "The first-response SLA is due within five minutes.",
        );
      }
      if (level > 0) {
        queueAlert(
          "SLA_BREACHED",
          level >= 3 ? "CRITICAL" : "HIGH",
          `The first-response SLA is breached at escalation level ${level}.`,
        );
      }
      if (level >= 2) {
        queueAlert(
          "MANAGER_ESCALATION",
          level >= 3 ? "CRITICAL" : "HIGH",
          `Manager review is required for escalation level ${level}.`,
        );
      }
    }
  }
  await Promise.all(operations);
}
